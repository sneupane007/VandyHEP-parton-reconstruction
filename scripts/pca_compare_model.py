"""PCA corner plot comparing hadron, true-parton and model-predicted-parton jets.

Each val event is summarized into per-event features (same as pca_analysis.py, minus
multiplicity — the model always emits all 24 slots, so predicted multiplicity is a constant
and would separate trivially). StandardScaler + PCA are fit on hadron + true parton ONLY,
then the predicted partons are projected into that fixed space, so the axes are set by the
truth and the plot shows where the model lands relative to it.

Run from the repo root:
  .venv/bin/python3 scripts/pca_compare_model.py [checkpoints/<run_dir>/checkpoint_best.pt]

Same val split as train.py/evaluate.py (match --val-fraction and --seed to the training run).

"""

import argparse
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(REPO_ROOT))

import matplotlib.pyplot as plt
import numpy as np
import torch
from sklearn.decomposition import PCA
from sklearn.preprocessing import StandardScaler
from torch_geometric.loader import DataLoader

from evaluate import split_dataset, wrap_phi
from parton_recon.data import JetPairDataset, LogPt
from parton_recon.models import build_model, predict_batched

GENERATED = REPO_ROOT / "parton_recon" / "data" / "generate"
N_COMPONENTS = 5

FEATURE_NAMES = [
    "multiplicity", "pt_mean", "pt_std", "eta_mean", "eta_std", "phi_circular_std", "jet_pt",
]

# multiplicity is column 0 of summarize_event; dropped, see module docstring
FEATURES = FEATURE_NAMES[1:]
# ("hadron", "#4C72B0")
LEVELS = [ ("true parton", "#55A868"), ("predicted parton", "#C44E52")]


def parse_args():
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("checkpoint", type=Path, nargs="?",
                   default=REPO_ROOT / "checkpoints" / "gnn_chamfer_20260928_235508" / "checkpoint_best.pt")
    p.add_argument("--hadron-json", type=Path, default=GENERATED / "model1_hadron_level_graphs_.json")
    p.add_argument("--parton-json", type=Path, default=GENERATED / "model1_parton_level_graphs_.json")
    p.add_argument("--val-fraction", type=float, default=0.2)
    p.add_argument("--seed", type=int, default=0)
    p.add_argument("--out", type=Path, default=None,
                   help="where to save the plot (default: pca_corner.png next to the checkpoint)")
    return p.parse_args()


def summarize_event(node_features):
    arr = np.asarray(node_features, dtype=float)
    pt, eta, phi = arr[:, 0], arr[:, 1], arr[:, 2]
    px, py = pt * np.cos(phi), pt * np.sin(phi)
    jet_pt = np.hypot(px.sum(), py.sum())
    resultant = np.hypot(np.cos(phi).mean(), np.sin(phi).mean())
    phi_circular_std = np.sqrt(-2 * np.log(resultant)) if resultant > 0 else 0.0
    return [len(pt), pt.mean(), pt.std(), eta.mean(), eta.std(), phi_circular_std, jet_pt]


def summaries(events):
    return np.array([summarize_event(e)[1:] for e in events])

# Generated by Sonnet 5.5 Medium
def corner_plot(scores, ratios, out_path):
    k = N_COMPONENTS
    fig, axes = plt.subplots(k, k, figsize=(2.2 * k, 2.2 * k))
    for i in range(k):
        for j in range(k):
            ax = axes[i, j]
            if j > i:
                ax.set_visible(False)
                continue
            for name, color in LEVELS:
                s = scores[name]
                if i == j:
                    # ax.hist(s[:, i], bins=30, density=True, histtype="step", color=color, label=name)
                    mu, sigma = s[:, i].mean(), s[:, i].std()
                    x = np.linspace(mu - 4 * sigma, mu + 4 * sigma, 200)
                    pdf = np.exp(-0.5 * ((x - mu) / sigma) ** 2) / (sigma * np.sqrt(2 * np.pi))
                    ax.plot(x, pdf, color=color, label=name)
                else:
                    ax.scatter(s[:, j], s[:, i], s=6, alpha=0.4, color=color)
            if i == k - 1:
                ax.set_xlabel(f"PC{j + 1} ({ratios[j]:.0%})")
            else:
                ax.set_xticklabels([])
            if j == 0 and i > 0:
                ax.set_ylabel(f"PC{i + 1} ({ratios[i]:.0%})")
            elif i != j:
                ax.set_yticklabels([])
    handles, labels = axes[0, 0].get_legend_handles_labels()
    fig.legend(handles, labels, loc="upper right", bbox_to_anchor=(0.95, 0.95))
    fig.tight_layout()
    fig.savefig(out_path, dpi=150)


def main():
    args = parse_args()
    out_path = args.out or args.checkpoint.parent / "pca_corner.png"

    device = torch.device("cuda" if torch.cuda.is_available()
                          else "mps" if torch.backends.mps.is_available() else "cpu")
    ckpt = torch.load(args.checkpoint, map_location=device, weights_only=False)
    model = build_model(ckpt["arch_config"]).to(device)
    model.load_state_dict(ckpt["model_state_dict"])
    model.eval()

    dataset = JetPairDataset(args.hadron_json, args.parton_json, transform=LogPt())
    val_set = split_dataset(dataset, args.val_fraction, args.seed)
    idx = val_set.indices

    batch = next(iter(DataLoader(val_set, batch_size=len(val_set), shuffle=False))).to(device)
    with torch.no_grad():
        pred = LogPt.inverse(predict_batched(model, batch))
    pred[..., 2] = wrap_phi(pred[..., 2])
    pred_events = [pred[i].cpu().numpy() for i in range(pred.shape[0])]

    # raw physical hadron/parton features straight from the JSON, in val-split order
    hadron = summaries([dataset.hadron[i]["node_features"] for i in idx])
    parton = summaries([dataset.parton[i]["node_features"] for i in idx])
    predicted = summaries(pred_events)

    scaler = StandardScaler().fit(np.vstack([parton, predicted]))
    pca = PCA(n_components=N_COMPONENTS).fit(scaler.transform(np.vstack([parton, predicted])))
    scores = {
        name: pca.transform(scaler.transform(x))
        for (name, _), x in zip(LEVELS, [parton, predicted])
    }

    ratios = pca.explained_variance_ratio_
    print(f"{len(idx)} val events, checkpoint epoch {ckpt['epoch']}")
    print("Explained variance ratio (fit on hadron + true parton):")
    for i, r in enumerate(ratios, start=1):
        print(f"  PC{i}: {r:.3f}")
    print("\nLoadings (rows = features):")
    print(f"  {'':>18} " + " ".join(f"{'PC' + str(i + 1):>7}" for i in range(N_COMPONENTS)))
    for f, name in enumerate(FEATURES):
        print(f"  {name:>18} " + " ".join(f"{pca.components_[c, f]:+7.3f}" for c in range(N_COMPONENTS)))

    corner_plot(scores, ratios, out_path)
    print(f"\nsaved plot to {out_path}")


if __name__ == "__main__":
    main()
